const tables: Record<Lang, Record<StringKey, string>> = { es, en };

export function strings(lang: Lang) {
  const table = tables[lang];
  /** Optional {placeholders} are filled from vars. */
  return (key: StringKey, vars?: Record<string, string | number>) =>
    vars ? table[key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? "")) : table[key];
}
export type T = ReturnType<typeof strings>;
